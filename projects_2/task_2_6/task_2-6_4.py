print("=== Витязь на распутье ===")
print("На камне высечено:")
print("\tкак пряму ехати — живу не бывати — нет пути ни проезжему, ни прохожему, ни пролетному;")
print("\tнаправу ехати — женату быти")
print("\tналеву ехати — богату быти")
print()

choice = input("Куда повернёт витязь? (направо/налево/прямо): ").strip().lower()

if choice == "направо" or choice == "право":
    print("\nВитязь повернул направо.")
    print("Ждёт его впереди свадьба да жена любимая.")
    print("Обрёл он счастье семейное, дом крепкий и детей малых.")

elif choice == "налево" or choice == "лево":
    print("\nВитязь повернул налево.")
    print("Ждёт его впереди богатство несметное.")
    print("Злато да серебро, каменья самоцветные — всего вдоволь.")

elif choice == "прямо" or choice == "вперёд":
    print("\nВитязь поехал прямо.")
    print("А там — погибель неминучая.")
    print("Ни проезжему, ни прохожему, ни пролётному пути оттуда нет.")

else:
    print("\nВитязь замер в раздумьях.")
    print("Стоит он у камня, не решаясь ступить ни на одну из дорог.")
    print("Так и остался он на распутье — ни женат, ни богат, ни мёртв.")